<?php

use App\Enums\AssignmentStatus;
use App\Enums\RunType;
use App\Models\Assignment;
use App\Models\Run;
use App\Models\Setting;
use Flux\Flux;
use Livewire\Attributes\Computed;
use Livewire\Attributes\Title;
use Livewire\Component;

new #[Title('Dashboard')] class extends Component {
    #[Computed]
    public function settings(): Setting
    {
        return Setting::current();
    }

    #[Computed]
    public function lastRun(): ?Run
    {
        return Run::query()->latest('id')->first();
    }

    /**
     * @return array<string, int>
     */
    #[Computed]
    public function counts(): array
    {
        return Assignment::query()
            ->selectRaw('status, count(*) as total')
            ->groupBy('status')
            ->pluck('total', 'status')
            ->all();
    }

    #[Computed]
    public function upcomingAssignments()
    {
        return Assignment::query()
            ->whereNotIn('status', [AssignmentStatus::Submitted])
            ->orderByRaw('due_at is null, due_at')
            ->limit(8)
            ->get();
    }

    public function runNow(): void
    {
        if (Run::query()->active()->exists()) {
            Flux::toast(variant: 'warning', text: __('A run is already queued or running.'));

            return;
        }

        $run = Run::queue(RunType::Manual);
        $this->redirectRoute('runs.show', $run, navigate: true);
    }
}; ?>

<div class="flex flex-col gap-6" wire:poll.10s>
    <div class="flex flex-wrap items-center justify-between gap-4">
        <div>
            <flux:heading size="xl" level="1">{{ __('Dashboard') }}</flux:heading>
            <flux:text class="mt-1">{{ __('Pending Moodle assignments and drafts generated by the worker.') }}</flux:text>
        </div>
        <flux:button variant="primary" icon="play" wire:click="runNow">{{ __('Run now') }}</flux:button>
    </div>

    <div class="grid gap-4 md:grid-cols-3">
        <flux:card class="space-y-2">
            <flux:subheading>{{ __('Worker') }}</flux:subheading>
            @if ($this->settings->workerOnline())
                <flux:badge color="green" icon="signal">{{ __('Online') }}</flux:badge>
            @else
                <flux:badge color="red" icon="signal-slash">{{ __('Offline') }}</flux:badge>
            @endif
            <flux:text>
                {{ __('Last seen') }}: {{ $this->settings->worker_seen_at?->diffForHumans() ?? __('never') }}
            </flux:text>
        </flux:card>

        <flux:card class="space-y-2">
            <flux:subheading>{{ __('Next runs') }}</flux:subheading>
            @forelse ($this->settings->upcomingRuns(3) as $at)
                <flux:text>{{ $at->translatedFormat('D, d/m H:i') }}</flux:text>
            @empty
                <flux:text>{{ __('Automatic runs are disabled.') }}</flux:text>
            @endforelse
            <flux:link :href="route('automation.edit')" wire:navigate class="text-sm">{{ __('Edit schedule') }}</flux:link>
        </flux:card>

        <flux:card class="space-y-2">
            <flux:subheading>{{ __('Last run') }}</flux:subheading>
            @if ($run = $this->lastRun)
                <div class="flex items-center gap-2">
                    <flux:badge :color="$run->status->color()" size="sm">{{ $run->status->label() }}</flux:badge>
                    <flux:text>{{ $run->type->label() }} · {{ $run->created_at->diffForHumans() }}</flux:text>
                </div>
                <flux:link :href="route('runs.show', $run)" wire:navigate class="text-sm">{{ __('View log') }}</flux:link>
            @else
                <flux:text>{{ __('No runs yet.') }}</flux:text>
            @endif
        </flux:card>
    </div>

    <div class="flex flex-wrap gap-2">
        @foreach (AssignmentStatus::cases() as $status)
            <flux:badge :color="$status->color()">
                {{ $status->label() }}: {{ $this->counts[$status->value] ?? 0 }}
            </flux:badge>
        @endforeach
    </div>

    <flux:card>
        <div class="mb-4 flex items-center justify-between">
            <flux:heading size="lg">{{ __('Open assignments') }}</flux:heading>
            <flux:link :href="route('assignments.index')" wire:navigate class="text-sm">{{ __('View all') }}</flux:link>
        </div>
        @include('partials.assignments-table', ['assignments' => $this->upcomingAssignments])
    </flux:card>
</div>
